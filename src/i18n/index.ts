i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'pt',
    debug: false, // Desativando debug
    
    interpolation: {
      escapeValue: false, // react already does escaping
    },
    
    detection: {
      order: ['localStorage', 'navigator', 'htmlTag'],
      caches: ['localStorage'],
      lookupLocalStorage: 'i18nextLng',
    },
    
    react: {
      useSuspense: false, // Desabilitar suspense para evitar problemas
    }
  });

// Forçar carregamento do idioma salvo
const savedLanguage = localStorage.getItem('i18nextLng');
const supportedLanguages = ['pt', 'en', 'es', 'fr', 'de', 'it'];

if (savedLanguage && supportedLanguages.includes(savedLanguage)) {
  i18n.changeLanguage(savedLanguage);
} else {
  // Se não há idioma salvo ou não é suportado, detectar automaticamente
  const browserLang = navigator.language.toLowerCase();
  let detectedLang = 'pt'; // fallback
  
  if (browserLang.includes('en')) detectedLang = 'en';
  else if (browserLang.includes('es')) detectedLang = 'es';
  else if (browserLang.includes('fr')) detectedLang = 'fr';
  else if (browserLang.includes('de')) detectedLang = 'de';
  else if (browserLang.includes('it')) detectedLang = 'it';
  
  i18n.changeLanguage(detectedLang);
  localStorage.setItem('i18nextLng', detectedLang);
}

